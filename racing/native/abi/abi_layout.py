class CarEffect(object):
    """ВНЕШНЕЕ ВОЗДЕЙСТВИЕ на одну машину — ДОЗА НА ОДИН ШАГ.
    
    Зачем структура существует. Всё, что в игре действует на машину извне —
    бонусы (турбо, ракета, мина, гроза), происшествия на дороге (масло,
    обломки, твёрдые препятствия), трамплины, — у классики делалось прямой
    правкой x/z/vx/vz и подменой характеристик МЕЖДУ шагами. У Rapier
    состояние машины внутри модуля, и этой двери нет. Здесь она одна на всех:
    хозяин кладёт дозу, модуль применяет её внутри своего шага.
    
    Три правила, на которых всё держится.
    
    1. НОЛЬ — ЭТО «НЕТ ВОЗДЕЙСТВИЯ». Каждое поле — доза, а не множитель:
       нулевая запись обязана считаться бит в бит так же, как считалась до
       появления этой структуры. Поэтому не grip_mul, а grip_drop.
    2. ДОЗА ЖИВЁТ ОДИН ШАГ. Модуль обнуляет запись после шага, а хозяин
       пишет её заново каждый тик, пока действие длится. Отсюда бесплатно
       получаются две вещи: откат клиента (переигранный тик получит ту же
       дозу, потому что таймер лежит в кольце хозяина, а не в модуле) и
       невозможность «применить дважды» — доза не копится.
    3. ЧИСЕЛ ИГРЫ ЗДЕСЬ НЕТ. Все величины приезжают снаружи, из game/items.py
       и game/physics.py (и зеркал в static/js). В модуле только механика —
       то же правило, по которому сделана награда за занос (§12.24).
    
    Чего в структуре НЕТ намеренно: адресата. Воздействие лежит в записи той
    машины, к которой относится, и применить его к чужой можно только написав
    в чужую запись — а пишет сюда один сервер.

    12 f32 = 48 байт.
    """

    SIZE = 48
    FLOATS = 12
    # --- управление ---
    # >0.5: ввод машины заглушён на этот шаг — ни газа, ни тормоза,
    # ни руля, ни ручника. Тот же смысл, что у шага 1 раздела 6.2:
    # раскрутка после попадания и жёсткая посадка отбирают управление.
    # Ручник глушится и для шага 15, иначе занос копился бы у того,
    # кто держал пробел в момент попадания.
    STUN = 0
    # принудительная угловая скорость вокруг мировой вертикали, рад/с.
    # Ноль — не крутить. Курс доворачивается КИНЕМАТИЧЕСКИ, как в
    # классике (yaw += SPIN_RATE*dt): скорость при этом не трогается,
    # машину разворачивает поперёк собственного хода, а боковое
    # сцепление уже само стаскивает её в новую сторону.
    # Число даёт хозяин: SPIN_RATE из game/physics.py.
    SPIN_RATE = 1
    # >0.5: копилка заноса сгорает БЕЗ выплаты, вместе со стороной.
    # Нужно там, где классика пишет state.drift_charge = 0 руками:
    # попадание ракеты или мины не должно обналичивать занос.
    DRIFT_RESET = 2
    # --- продольная динамика ---
    # сколько секунд ускорения выдать машине. Правило то же, что у
    # награды за занос: новый буст не укорачивает уже идущий, берётся
    # максимум. Ноль — ничего не выдавать.
    # Число даёт хозяин: BOOST_TIME из game/items.py.
    BOOST_ADD = 3
    # доля ПРОДОЛЬНОЙ скорости, снимаемая за этот шаг (0 — ничего).
    # Одно поле на «Грозу» (1 - SLOW_FACTOR) и на тряску по обломкам
    # (1 - DEBRIS_DAMP): это одно и то же воздействие с разными
    # числами. В воздухе не снимается — тормозить нечем, ровно как
    # шаг 8 раздела 6.2. Обрезается в 0..1: разгонять «замедлением»
    # отрицательной дозой нельзя.
    SPEED_DROP = 4
    # --- покрытие ---
    # доля сцепления, которую съедает покрытие под машиной, 0..1.
    # Множит и friction_slip, и side_friction_stiffness всех четырёх
    # колёс на (1 - grip_drop). Масло, обломки; сюда же ляжет всё,
    # что в классике делалось через car.slippery(scale) ДО шага.
    # Погода сюда НЕ идёт: она живёт в трении сетки полотна (§12.24),
    # одна на всю трассу и на обе стороны.
    GRIP_DROP = 5
    # --- толчок ---
    # мгновенное приращение скорости центра масс, м/с, в мировых осях.
    # Не сила и не импульс: скорость, чтобы число не зависело от массы
    # машины и читалось так же, как state.vx у классики. Отсюда поедут
    # отдача от твёрдого препятствия, отброс взрывом и вылет с
    # трамплина (это push_y).
    PUSH_X = 6
    PUSH_Y = 7
    PUSH_Z = 8
    # мгновенное приращение ПОЗИЦИИ, м, в мировых осях. Применяется
    # до шага солвера, поэтому перекрытие он доразведёт сам. Нужно
    # выталкиванию из твёрдого препятствия: снять перекрытие одной
    # скоростью нельзя — машина сначала пройдёт сквозь.
    SHIFT_X = 9
    SHIFT_Y = 10
    SHIFT_Z = 11


