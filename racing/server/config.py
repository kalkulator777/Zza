# Множитель сцепления по погоде: попадает в физику через крюк, который по
# умолчанию равен 1,0 (сухо). Трогает ТОЛЬКО цепкость — мощность, тормоза
# и масса не меняются, иначе мокрая трасса превратилась бы в другую игру.
#
# Числа выбраны от предела поперечного ускорения (6.2: a_lat = grip_step *
# GRIP_LAT_ACCEL): скорость в повороте радиуса R падает как корень из
# множителя, поэтому 0,86 стоит около 7 % скорости в дуге, а 0,72 — около
# 15 %. Первое — «надо аккуратнее», второе — «надо по-другому».
#
# Это КОНТРАКТНАЯ таблица, но сервер не единственный, кто её знает: физика
# лежит в game/ и про server/ ничего не знает, а клиент считает те же шаги
# у себя. Поэтому таблица повторена в game/physics.py и static/js/physics.js
# ровно так же, как TIMES_OF_DAY повторено в game/track.py. Меняя число
# здесь, поменяйте во всех трёх местах: расхождение даёт рассинхрон
# предсказания с сервером, а не косметику.
WEATHER_GRIP = {
    'clear': 1.0,
    'wet': 0.86,
    'snow': 0.72,
    'fog': 1.0,
}


def weather_grip(weather):
    """Множитель сцепления по названию погоды. Мусор — это сухо (1,0)."""
    return WEATHER_GRIP.get(weather, 1.0)

