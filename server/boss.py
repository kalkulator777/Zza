# -*- coding: utf-8 -*-
"""Босс: вершина забега (DESIGN.md 8.1 «босс на каждом пятом этаже»).

ЧТО ЗДЕСЬ РЕШЕНО И ПОЧЕМУ

**БОСС — ЭТО НЕ ТОЛСТЫЙ РУБАКА.** Рубаку с 400 hp игрок бьёт и отходит,
бьёт и отходит; бой сводится к одному движению и к делению 400 на 20.
Поэтому у босса ДВЕ атаки, и они требуют ПРОТИВОПОЛОЖНОГО движения:

  * **«Обвал»** — удар по земле ВОКРУГ СЕБЯ, круг радиуса SLAM_R.
    Ответ — **разорвать дистанцию**: бежать (или рвануть) ПРОЧЬ. Уход вбок
    не спасает: из круга вбок не выходят.
  * **«Залп»** — три снаряда веером по направлению, замороженному на
    замахе. Ответ — **уйти С ЛИНИИ, вбок**. Отступление по прямой не
    спасает: снаряд летит 18 кл/с, игрок бежит 7.5.

Ровно эта пара и есть «бой не про цифры»: правильный ответ на одну атаку
является неправильным ответом на другую, и выбирать приходится по тому,
ЧТО босс начал делать и НА КАКОМ расстоянии. Арифметика обоих уходов
выписана ниже у констант и проверяется числами в tests/boss_check.py.

**ЧИТАЕМОСТЬ — ПО ТЕМ ЖЕ ПРАВИЛАМ, ЧТО У РЯДОВОГО ВРАГА.**
Оба замаха поднимают бит `F_WINDUP` (4.3) и держат его весь замах, на замахе
босс СТОИТ и направление у него заморожено, как у стрелка: видно не только
«сейчас ударит», но и куда.

ЗАМАХИ — 12 ТИКОВ, А НЕ 18, И ЭТО ПЛАТА ЗА ТЕМП, А НЕ ПОБЛАЖКА.
Замах меряется тиками, уход — клетками, и при беге 7.5 кл/с (world.SPEED_K)
за 18 тиков игрок проходит 4.50 клетки вместо 3.00. Круг «Обвала» стоит на
том, что ВБОК ИЗ НЕГО НЕ ВЫЙТИ: hypot(1.70, 4.50) = 4.81 больше порога 4.00,
то есть уход вбок начал спасать — а это ровно та поломка, при которой бой с
боссом становится одномерным (проверяется таблицей 2x2 в boss_check).
Лечится это одним из двух: растить круг или укорачивать замах.

Круг растить НЕЛЬЗЯ: чтобы вбок снова не выходило, нужен порог 5.45, а
уйти от такого круга можно только в комнате стороной 11 — тогда как арена
по 8.1 бывает и 8 (gen.ARENA_MIN_SIDE, замер: медиана лучшей комнаты 11,
минимум 8). Босс, от «Обвала» которого на трети этажей уйти нельзя вовсе, —
это не бой, а налог.

Поэтому укорочены ОБА замаха: 12 тиков дают ровно прежние 3.00 клетки
ухода, и вся геометрия боя (SLAM_R 3.65, порог 4.00, VOLLEY_NEAR 4.2, веер
20 градусов, арена 8) остаётся ТОЧНО прежней — ни одно расстояние в этом
файле не пересчитано, пересчитаны только два числа тиков. Цена названа
честно: на реакцию у игрока 0.4 с вместо 0.6. Это нижний край вилки 4.2
(«замах врага 12–18 тиков»), тот же, что у рубаки, и он всё ещё вдвое
больше рывка (5 тиков).

У залпа для укорочения есть и своя причина, не только общая, — см. вывод
VOLLEY_SPREAD: на 18 тиках отступление по прямой начинало СПАСАТЬ, потому
что убегающий игрок уходил за дальность снаряда.

Различить атаки игрок может ДО удара и без единого нового поля на проводе:
они живут на дистанциях, разделённых КРОМКОЙ КРУГА. Всё, что ближе 4.00
клетки (радиус «Обвала» плюс радиус игрока), может быть только «Обвалом»:
«Залп» ближе VOLLEY_NEAR = 4.2 не начинается вовсе. Правило игрока поэтому
одно и без исключений: **я внутри круга — выхожу из круга, я снаружи —
ухожу с линии**. Полоса, в которой замах бывает любым, отсутствует — и это
не мелочь: пока она была (3.5..4.0), скриптовый боец ловил «Обвал» на
3.37-3.41, потому что честно отвечал на него ответом для «Залпа».

**РАЗМЕР.** Радиус 0.50 против 0.35 у рядового: площадь тела вдвое (2.04).
0.50 — не круглое число, а ПОТОЛОК: это самый крупный круг, который ещё
проходит коридор в одну клетку с подталкиванием 4.2a. Замерено на карте с
единственным проёмом, 16 заходов с разных сторон: r=0.50 — 16/16 (медиана
68 тиков), r=0.55 — 0/16. Крупнее — и босс встал бы в первой же двери, то
есть сломал бы ровно то, что 4.2a чинит. Поэтому босс ходит везде, где
ходит рядовой враг, и никакой особой физики ему не нужно.

**СКОРОСТЬ 6.3 кл/с** (было 4.2; тот же множитель 1.5, что у всех скоростей,
см. world.SPEED_K). 4.2 обещает «убежать можно всегда»: босс медленнее
игрока (7.5) и обещание держит. Но он БЫСТРЕЕ рубаки (4.8) намеренно:
разрыв всего 1.2 кл/с, то есть одна дистанция «Обвала» (3.65 клетки)
покупается 3.0 секундами бега — за это время босс успевает дать залп.
Убежать можно, отстреливаться на бегу бесконечно — нет.

**ВИДИТ И СЛЫШИТ ОН ТАК ЖЕ, КАК ВСЕ.** Ни одного луча: зрение — байт тумана
(4.4), слух — волна шума (8.2), путь — общая волна (8.3). Босс проходит по
тем же спискам ai.step, что и рядовые; отдельного цикла у него нет.

**ЛЕСТНИЦА ЗАПЕРТА, ПОКА БОСС ЖИВ** — world.on_stairs. Иначе босса можно
обойти, а обойдённый босс это отсутствующий босс.
"""

import math

from . import combat
from . import physics
from . import world as world_mod

K_BOSS = world_mod.K_BOSS
F_WINDUP = world_mod.F_WINDUP

# --- где он встречается (8.1) ---------------------------------------------
BOSS_EVERY = 5          # «на каждом пятом этаже»


def on_floor(floor):
    """Есть ли босс на этаже такой глубины. Единственный источник правды."""
    f = int(floor)
    return f > 0 and f % BOSS_EVERY == 0


# --- тело -----------------------------------------------------------------
BOSS_R = 0.50
# ВЫВОД BOSS_R: потолок проходимости, а не вкус. Полоса свободного прохода
# для центра в коридоре шириной 1 клетка равна 1 - 2r (4.2a); при r = 0.50
# она нулевая, и тело проходит только подталкиванием — оно и проводит
# (16/16). При r = 0.55 полоса отрицательная, проход невозможен физически
# (0/16). Единственная живая тема "halls" делает коридоры шириной 1
# (gen.Theme.corridor_w), так что 0.50 — предел для всей карты.

BOSS_HP = 400
# ВЫВОД BOSS_HP — ОТ ТЕМПА, А НЕ ОТ «ХОЧУ ДОЛГО». Это 20 ударов игрока по 20
# (4.2) или 34 снаряда по 12. Между «Обвалами» (SLAM_CD = 54 тика) игрок,
# который подходит, бьёт и уходит, успевает 2-3 удара при откате удара 14
# тиков.
#
# ЧТО СДЕЛАЛ С ЭТИМ ПОДНЯТЫЙ ТЕМП — ЗАМЕРЕНО, А НЕ ОЦЕНЕНО (скриптовый боец,
# tests/boss_check.py, раздел 5):
#
#   было (5.0 кл/с):  бой 19.5 с, 20.5 hp/с, игрок выходит с 50 hp из 100
#   стало (7.5 кл/с): бой 16.4 с, 24.3 hp/с, игрок выходит с 75 hp
#
# Подходы и отходы стали короче по времени, а босс бьёт по-прежнему раз в 54
# и 75 тиков — значит на тот же бой приходится меньше его атак. Босс подешевел
# на один «Обвал»: 16% времени и один удар из двух. Это НЕ исправлено здесь
# намеренно: 400 — контрактное число (4.2), и поднимать его до 480 (столько
# нужно, чтобы бой снова длился 19.5 с) — решение дирижёра, а не правка по
# дороге. Число вынесено в отчёт.

BOSS_SPEED = 6.3        # кл/с; игрок 7.5, рубака 4.8 (4.2)
BOSS_STOP = 1.05        # ближе не подходит: 0.50 + 0.35 тел плюс зазор

# --- «Обвал»: круг вокруг себя --------------------------------------------
SLAM_WIND = 12          # тиков; НИЖНИЙ край вилки 4.2 (12-18), вывод в шапке
SLAM_CD = 54            # 1.8 с между обвалами
SLAM_START = 3.2        # с этой дистанции начинает замах
SLAM_R = 3.65           # радиус круга от центра тела; до цели +её радиус
SLAM_DMG = 25           # 4 обвала по игроку в 100 hp
# ВЫВОД SLAM_R. Порог попадания = SLAM_R + радиус игрока 0.35 = 4.00 клетки.
# Считано от трёх движений игрока за 12 тиков замаха (7.5 кл/с * 0.4 с =
# 3.00 клетки — ровно столько же, сколько давали прежние 5.0 кл/с за 18
# тиков), от дистанции удара (combat.MELEE_REACH 1.2 + BOSS_R 0.50 = 1.70 —
# ровно там игрок стоит, когда бьёт босса):
#   стоять на месте          1.70            -> накрыт
#   бежать ВБОК     hypot(1.70, 3.00) = 3.45 -> накрыт (запас 0.55, 14%)
#   бежать ПРОЧЬ      1.70 + 3.00     = 4.70 -> ушёл   (запас 0.70, 18%)
#   рывок прочь  1.70 + 3.50 + 1.75   = 6.95 -> ушёл с большим запасом
# То есть круг НЕЛЬЗЯ обойти сбоку и МОЖНО разорвать — это и делает «Обвал»
# атакой про дистанцию. Меньше 3.45 — и обвал обходится вбок, то есть
# перестаёт отличаться от удара рубаки; больше 4.70 — и от него нельзя уйти
# вовсе, а неотвратимый удар это не бой, а налог.

# --- «Залп»: веер снарядов ------------------------------------------------
VOLLEY_WIND = 12        # тиков, тот же нижний край вилки 4.2, что у «Обвала»
VOLLEY_CD = 75          # 2.5 с между залпами
VOLLEY_NEAR = 4.2       # ближе не стреляет: там его дело — «Обвал»
# ВЫВОД VOLLEY_NEAR — ЭТО ПРАВИЛО ЧТЕНИЯ, А НЕ ВКУС. Игрок отличает атаки по
# дистанции (нового поля на проводе для этого нет и не нужно), и правило
# должно быть однозначным на КАЖДОЙ дистанции: «я внутри круга — выхожу из
# круга, я снаружи — ухожу с линии». Значит нижняя граница залпа обязана
# лежать не ближе кромки круга: SLAM_R + радиус игрока = 3.65 + 0.35 = 4.00.
# 4.2 — она же плюс запас 0.2 на то, что между началом замаха и тем тиком,
# на котором игрок увидел бит, дистанция успевает чуть подрасти. Поставь
# сюда 3.5 — и появится полоса 3.5..4.0, где замах может оказаться любым из
# двух, а правильный ответ на один неверен для другого: замерено, скриптовый
# боец ловил «Обвал» ровно на 3.37-3.41.
VOLLEY_FAR = 12.0       # дальше не стреляет: снаряд живёт 14 клеток (4.2)
VOLLEY_N = 3            # снарядов в веере
VOLLEY_SPREAD = math.radians(20.0)      # угол между соседними снарядами
VOLLEY_DMG = 10         # на снаряд; втрое меньше «Обвала», зато достаёт
VOLLEY_LOS_EVERY = 3    # луч на выстрел — раз в 3 тика, как у стрелка
# ВЫВОД VOLLEY_SPREAD. Игрок уходит с линии бегом вбок: 3.00 клетки за 12
# тиков замаха (7.5 кл/с * 0.4 с — ровно столько же, сколько давали прежние
# 5.0 кл/с за 18 тиков). На дистанции залпа 5.0 это уводит его на 5.83
# клетки от босса и на 3.00 клетки от центральной линии; крайний снаряд на
# том же расстоянии стоит в 5.83 * tan(20 градусов) = 2.12 от линии, то есть
# в 0.88 клетки от игрока при полосе попадания 0.12 + 0.35 = 0.47. Запас
# 0.41 клетки. Шире веер — и уход вбок перестаёт работать (при 30 градусах
# крайний снаряд оказывается в 0.11 от игрока, то есть накрывает его);
# уже — и веер перестаёт наказывать полумеры.
#
# ЗАМАХ ЗАЛПА УКОРОЧЕН ВМЕСТЕ С «ОБВАЛОМ», И ПО ВТОРОЙ ПРИЧИНЕ. У круга от
# длины замаха зависело, не начнёт ли работать НЕВЕРНЫЙ ответ; у веера — не
# перестанет ли работать ПРАВИЛО «отступление по прямой не спасает». Оно
# держится на дальности снаряда: 14 клеток, и растить её нельзя, 8.2 ставит
# её ниже слышимости выстрела 18 намеренно. Считаем: при замахе 18 тиков
# убегающий игрок к выстрелу уже в 9.25 клетки, снаряд догоняет его на
# 15.9 клетки пути — то есть РАСТВОРЯЕТСЯ, не догнав, и отступление от
# залпа начинает спасать. При 12 тиках он в 7.75, снаряд догоняет на 13.3
# при дальности 14 — ровно тот же запас 5%, что был на прежнем темпе.
# Замерено таблицей 2x2 в tests/boss_check.py: 18 тиков дают ноль в клетке
# «залп / отступить», 12 — законные 10.
# ВЫВОД VOLLEY_DMG: три снаряда по 10 — это 30 по игроку в 100 hp, если
# стоять столбом и поймать все три. Поймать все три нельзя (они расходятся),
# один снаряд стоит 10 — вдвое меньше «Обвала», потому что уйти от линии
# дешевле, чем разорвать круг.


# --- заведение ------------------------------------------------------------

def make(w, x, y):
    """Завести босса. Урон он получает и наносит через тот же combat."""
    e = w.spawn(K_BOSS, x, y, r=BOSS_R, speed=BOSS_SPEED,
                hp=BOSS_HP, hp_max=BOSS_HP,
                # параметры СОБСТВЕННОЙ ближней атаки (world.Entity,
                # combat._land_melee): круг, а не дуга, — atk_cos = -1.0
                atk_r=SLAM_R, atk_cos=-1.0, atk_dmg=SLAM_DMG)
    e.ai = AI_BOSS
    return e


AI_BOSS = 3             # продолжает ai.AI_* ; серверное, на проводе нет


def spawn_on(w, fl):
    """Поставить босса на этаже, если этаж пятый. Возвращает сущность/None.

    Место — АРЕНА (gen: комната лестницы, выбранная по размеру и очищенная
    от столбов). Босс встаёт в её центре, а не на самой лестнице: на
    лестнице он закрыл бы телом клетку, на которую группе потом вставать.
    """
    if not on_floor(getattr(fl, "floor", 1)):
        return None
    room = getattr(fl, "boss_room", -1)
    rooms = getattr(fl, "rooms", None)
    if room is None or room < 0 or not rooms:
        return None
    r = rooms[room]
    cx = (r[0] + r[2]) * 0.5 + 0.5
    cy = (r[1] + r[3]) * 0.5 + 0.5
    x, y = physics.free_spot(w.grid, cx, cy, BOSS_R)
    return make(w, x, y)


# --- тик ------------------------------------------------------------------

def step(w, e, target, d, tick, grid, step_dir, line_clear):
    """Один тик босса. Зовётся из ai.step, состав мира не меняет.

    Снаряды веера не рождаются здесь: в очередь кладётся СПИСОК (угол,
    урон), а разбирает его combat.resolve после прохода по словарю — то же
    место и то же правило, что у выстрела игрока и стрелка.
    """
    if e.atk_hit:
        # «Обвал» на замахе: стоим. Направление для круга не важно, но
        # неподвижность важна — по ней игрок и читает, что сейчас рванёт.
        e.vx = e.vy = 0.0
        return
    if e.ai_wind:
        # «Залп» на замахе: стоим, ствол заморожен
        e.vx = e.vy = 0.0
        if tick >= e.ai_wind:
            e.ai_wind = 0
            e.flags &= ~F_WINDUP
            half = (VOLLEY_N - 1) * 0.5
            e.shot_q = [((i - half) * VOLLEY_SPREAD, VOLLEY_DMG)
                        for i in range(VOLLEY_N)]
            e.shot_ready = tick + VOLLEY_CD
        return

    if d <= SLAM_START and tick >= e.atk_ready:
        e.vx = e.vy = 0.0
        e.facing = math.atan2(target.y - e.y, target.x - e.x)
        combat.start_melee(w, e, windup=SLAM_WIND, cd=SLAM_CD)
        return

    if (VOLLEY_NEAR <= d <= VOLLEY_FAR and tick >= e.shot_ready
            and not ((tick + e.id) % VOLLEY_LOS_EVERY)
            and line_clear(grid, e.x, e.y, target.x, target.y)):
        e.vx = e.vy = 0.0
        e.facing = math.atan2(target.y - e.y, target.x - e.x)
        e.ai_wind = tick + VOLLEY_WIND
        e.flags |= F_WINDUP
        return

    if d <= BOSS_STOP:
        e.vx = e.vy = 0.0
        e.facing = math.atan2(target.y - e.y, target.x - e.x)
        return
    gx, gy, _ = step_dir(e.x, e.y)
    if gx or gy:
        e.vx = gx * e.speed
        e.vy = gy * e.speed
        e.facing = math.atan2(gy, gx)
    else:
        e.vx = e.vy = 0.0
