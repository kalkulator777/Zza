# -*- coding: utf-8 -*-
"""Предметы и апгрейды забега (DESIGN.md 8.4).

Внутри забега, без мета-прогрессии. Апгрейды СКЛАДЫВАЮТСЯ: второй такой же
не заменяет первый, а удваивает число, и это единственное правило, которое
здесь нельзя нарушать — на нём держится смысл второго забега.

ЧЕТЫРЕ АПГРЕЙДА, И ВСЕ ЧЕТЫРЕ МЕНЯЮТ ПРАВИЛО, А НЕ ПРОЦЕНТ. 8.4 писался до
того, как появился бой, и разрешает «модификаторы характеристик»; но +10% к
урону через десять минут не делает игру другой, а ради этого в рогалик и
играют второй раз. Поэтому три из четырёх апгрейдов меняют правило, и один
(«Ветер») — число, но в разы:

* **Жатва** — убийство лечит на HARVEST_HEAL за стак. Правило, которое это
  отменяет: «внутри этажа здоровье не восстанавливается» (8.5 даёт лечение
  только смертью и спуском). Самоограничение встроено: лечит не попадание, а
  ДОБИВАНИЕ, то есть ровно то действие, которое и так убирает урон с поля.
* **Таран** — рывок наносит RAM_DMG за стак каждому телу, сквозь которое
  прошёл, по разу за рывок. Правило, которое это меняет: рывок из бегства
  (неуязвимость, 4.2) становится оружием. Тела врагов для игрока проницаемы
  (расталкиваются только враги между собой, 4.2a), так что «сквозь» здесь —
  не фигура речи.
* **Рикошет** — снаряд не гибнет о стену, а отскакивает RICO_BOUNCES раз за
  стак. Правило, которое это меняет: 4.2a «прямая линия входит в смысл
  снаряда» — теперь только до первой стены. Дальность НЕ растёт: живёт
  снаряд по-прежнему ttl тиков (14 клеток), меняется лишь то, чем кончается
  встреча со стеной.
* **Ветер** — откат рывка DASH_CD / (1 + стаки). Это число, а не правило, и
  взят он ради сочетания: Ветер + Таран превращает рывок в основное оружие,
  а Ветер + Рикошет — в способ разорвать дистанцию и достать из-за угла.
  Вместе с ним приходит единственное ОГРАНИЧЕНИЕ в этом файле: неуязвимость
  рывка не имеет права занять больше половины отката (DASH_INV_SHARE), иначе
  сложенный трижды Ветер превращает уход в постоянный щит — замерено, было
  71% времени и бессмертие в кольце из двенадцати рубак.

ЦЕНА. «Апгрейд, который падает в руки» — это подарок, а не решение, поэтому
предметы лежат на АЛТАРЕ: ALTAR_SLOTS штуки разных видов в одной комнате,
берётся ОДИН — остальные гаснут в тот же тик. Платит игрок дважды:

* отказом: 2 из 3 апгрейдов этажа теряются навсегда;
* крюком: алтарь ставится в комнате с наибольшим КРЮКОМ с дороги вниз (см.
  gen._pick_altar), то есть за него платят временем в темноте и врагами,
  которых можно было обойти. Отказаться от крюка — законный ход: тогда этаж
  проходится быстрее, но забег остаётся прежним.

Кровью алтарь не берёт СОЗНАТЕЛЬНО: здоровье внутри этажа не
восстанавливается (8.5), фиксированная цена в hp за 4-5 этажей превратила бы
апгрейды в спираль смерти, а Жатву — в обязательный первый выбор.

НА ПРОВОДЕ. Предмет — обычная сущность (4.3): свой `kind` на каждый вид,
ровно по тому же доводу, по которому 4.2 развёл рубаку и стрелка разными
значениями `kind`, а не битом в `flags`, — игрок обязан ВИДЕТЬ, что он
выбирает, до того как нажмёт. Незнакомый `kind` клиент рисует серым кружком
(4.3), то есть старый клиент от новых предметов не падает, а новый рисует их
как захочет. Подбор уходит событием `pick` (5.2): восстановить его из
снапшота нельзя — предмет просто исчезает.

ЧЕГО НА ПРОВОДЕ НЕТ: набора апгрейдов игрока. 4.3 даёт ровно десять полей, и
одиннадцатого («что я собрал») там нет, а 5.2 запрещает держать состояние на
событиях. Правка контракта предложена в отчёте; пока `pick` несёт `u` (вид)
и `n` (сколько стало), так что потерянное событие чинится следующим.
"""

import random

from . import proto
from . import world as world_mod

# --- виды апгрейдов --------------------------------------------------------
U_HARVEST = 0
U_RAM = 1
U_RICO = 2
U_WIND = 3
N_UP = 4

NAMES = ("Жатва", "Таран", "Рикошет", "Ветер")

# kind предмета = K_ITEM_BASE + вид апгрейда (4.3: значения 1..5 заняты)
K_ITEM_BASE = 6
K_ITEM_LAST = K_ITEM_BASE + N_UP - 1

# --- числа эффектов --------------------------------------------------------
# Все взяты от существующих чисел 4.2, и каждое названо в разах.

# Жатва: 15 hp за убитого. ВЫВОД: рубака бьёт на 20 раз в 36 тиков = 16.7
# hp/с, а умирает от двух ударов игрока (40 hp / 20) = 28 тиков = 0.93 с.
# Значит один стак Жатвы возвращает 15 / 0.93 = 16.1 hp/с — ровно дыхание
# ОДНОГО рубаки в упор. Больше — и толпа перестаёт быть опасной; меньше —
# и лечение не читается.
HARVEST_HEAL = 15

# Таран: 20 за тело = ровно ближний удар (MELEE_DMG, 4.2). Рубака (40 hp)
# умирает от «рывок + удар», стрелок (25 hp) — нет: 20 < 25, и это
# намеренно, иначе рывок обнулял бы весь дальний бестиарий с одного стака.
RAM_DMG = 20

# Рикошет: 2 отскока за стак. ВЫВОД: Г-образный коридор — это два поворота,
# то есть двух отскоков хватает, чтобы достать из-за угла и вернуться.
RICO_BOUNCES = 2

# Ветер: откат рывка делится на (1 + стаки). Пол — DASH_CD_FLOOR тиков:
# ниже длительности рывка (5 тиков, 4.2) откат опускать нельзя, иначе рывок
# становится не рывком, а способом передвижения. 7 = 5 тиков рывка + 2 паузы.
DASH_CD_FLOOR = 7

# ДОЛЯ НЕУЯЗВИМОСТИ ОГРАНИЧЕНА ПОЛОВИНОЙ ОТКАТА, И ЭТО НЕ ВКУС.
# Рывок даёт неуязвимость на все свои 5 тиков (4.2). Ветер откат укорачивает,
# а окно неуязвимости — нет, поэтому её ДОЛЯ растёт сама собой: при откате 27
# это 18% времени, при 14 — 36%, при 7 — 71%. Замерено, что 71% и есть
# поломка, которой боится приёмка: игрок с Ветром x3 и Тараном выходит живым
# и со 100 hp из приклеенного кольца ИЗ ДВЕНАДЦАТИ рубак (tests/items_check,
# раздел 6). Поэтому неуязвимость режется до половины отката: половина —
# наименьшая доля, при которой «рывок — это уход, а не щит» остаётся правдой,
# ведь вторую половину времени урон проходит. При откате 27/14/10 ничего не
# меняется вовсе (5 <= cd//2), режется только выжатый Ветром хвост.
DASH_INV_SHARE = 2      # неуязвимость <= откат / DASH_INV_SHARE

# --- алтарь ----------------------------------------------------------------
ALTAR_SLOTS = 3        # предметов на алтаре; берётся один
ITEM_R = 0.20          # радиус сущности предмета: меньше тела, это не тело
PICK_R = 0.80          # с какого расстояния предмет берётся
# ВЫВОД PICK_R: предмет стоит в центре клетки, радиус игрока 0.35 (4.1).
# 0.80 — это «стою на клетке предмета или вплотную к ней»: центр игрока
# может отойти от центра клетки на 0.5*sqrt(2)=0.71 и всё ещё стоять на
# ней. Меньше 0.71 — и предмет нельзя взять, стоя на нём по диагонали.
MAX_PICKUPS = 16       # предохранитель очереди, как у world.MAX_NOISES


def kind_of(u):
    """Вид апгрейда -> kind сущности предмета (4.3)."""
    return K_ITEM_BASE + u


def up_of(kind):
    """kind сущности -> вид апгрейда, или -1 если это не предмет."""
    u = kind - K_ITEM_BASE
    return u if 0 <= u < N_UP else -1


def is_item(kind):
    return K_ITEM_BASE <= kind <= K_ITEM_LAST


# --- состояние владельца ---------------------------------------------------
# Хранится в e.ups: None (ничего не собрано) или список счётчиков длины N_UP.
# Список, а не набор флагов, именно потому, что 8.4 требует СКЛАДЫВАНИЯ:
# «есть апгрейд» — это число, а не да/нет.

def count(e, u):
    ups = e.ups
    return ups[u] if ups else 0


def total(e):
    ups = e.ups
    return sum(ups) if ups else 0


def grant(e, u, n=1):
    """Выдать n стаков апгрейда. Возвращает, сколько стало."""
    if not (0 <= u < N_UP):
        return 0
    ups = e.ups
    if ups is None:
        ups = [0] * N_UP
        e.ups = ups
    ups[u] += n
    return ups[u]


def describe(e):
    """Читаемый набор: [(вид, сколько)] — для отчётов и проверок."""
    ups = e.ups
    if not ups:
        return []
    return [(u, ups[u]) for u in range(N_UP) if ups[u]]


# --- эффекты: единственное место, где апгрейд превращается в число ---------
# Бой зовёт эти функции, а не заглядывает в e.ups. Поэтому «апгрейд не
# применился» и «апгрейд не сложился» — две разные поломки в двух разных
# строках, и проверка умеет отличить одну от другой.

def kill_heal(e):
    """Сколько hp возвращает убийство (Жатва). 0 — апгрейда нет."""
    return HARVEST_HEAL * count(e, U_HARVEST)


def dash_dmg(e):
    """Урон рывка по телу на пути (Таран). 0 — апгрейда нет."""
    return RAM_DMG * count(e, U_RAM)


def shot_bounces(e):
    """Сколько раз снаряд отскочит от стены вместо гибели (Рикошет)."""
    return RICO_BOUNCES * count(e, U_RICO)


def dash_cd(e, base):
    """Откат рывка с учётом Ветра. base — число тиков из combat (4.2)."""
    k = count(e, U_WIND)
    if not k:
        return base
    cd = int(round(base / float(1 + k)))
    return cd if cd > DASH_CD_FLOOR else DASH_CD_FLOOR


def dash_inv(base_inv, cd):
    """Сколько тиков длится неуязвимость рывка при таком откате.

    Без Ветра возвращает ровно base_inv (число 4.2): 5 <= 27 // 2. Смысл
    появляется только на укороченном откате — см. DASH_INV_SHARE.
    """
    half = cd // DASH_INV_SHARE
    if base_inv <= half:
        return base_inv
    return half if half >= 1 else 1


# --- лечение ---------------------------------------------------------------

def heal(e, amount):
    """Добавить hp, не выше hp_max. Возвращает, сколько добавилось на самом деле.

    Мёртвый не лечится: 8.5 говорит, что дух воскресает этажом ниже, а не от
    чужой смерти. Иначе Жатва воскрешала бы напарника чужим убийством.
    """
    if amount <= 0 or e.hp <= 0 or (e.flags & world_mod.F_DEAD):
        return 0
    hp = e.hp + amount
    if hp > e.hp_max:
        hp = e.hp_max
    got = hp - e.hp
    e.hp = hp
    return got


# --- рывок-таран -----------------------------------------------------------

def dash_strike(w, e, damage_fn):
    """Урон телам, сквозь которые прошёл рывок. Раз за рывок на тело.

    Зовётся из combat.resolve, то есть ПОСЛЕ движения: тело уже там, где
    оно оказалось в этом тике. Список уже задетых живёт в e.dash_hit и
    обнуляется на старте рывка — без него один рывок бил бы одну и ту же
    цель все 5 тиков, то есть впятеро.
    """
    dmg = dash_dmg(e)
    if dmg <= 0:
        return 0
    hits = e.dash_hit
    if hits is None:
        hits = []
        e.dash_hit = hits
    n = 0
    for t in w.entities.values():
        if t is e or t.id in hits:
            continue
        if t.kind == world_mod.K_SHOT or not t.team or t.team == e.team:
            continue                 # свои и снаряды тараном не берутся
        if t.flags & world_mod.F_DEAD:
            continue
        dx = t.x - e.x
        dy = t.y - e.y
        rr = e.r + t.r
        if dx * dx + dy * dy > rr * rr:
            continue
        hits.append(t.id)
        if damage_fn(w, t, dmg, e):
            n += 1
    return n


# --- подбор (бит 16 в btn, 5.1) -------------------------------------------

def request_pickup(w, e):
    """Кнопка предмета нажата. Сам подбор — в resolve_pickups.

    Класть предмет в руки прямо здесь нельзя: begin() зовётся ИЗ цикла по
    словарю сущностей (world.step), а подбор этот словарь меняет — предмет
    исчезает, и вместе с ним его собратья по алтарю. Та же причина, по
    которой снаряд рождается в resolve, а не в begin.
    """
    if len(w.pickups) < MAX_PICKUPS:
        w.pickups.append(e.id)


def nearest_item(w, e):
    """Ближайший предмет в радиусе PICK_R, или None."""
    best = None
    best_d2 = PICK_R * PICK_R
    for t in w.entities.values():
        if not is_item(t.kind):
            continue
        dx = t.x - e.x
        dy = t.y - e.y
        d2 = dx * dx + dy * dy
        if d2 <= best_d2:
            best_d2 = d2
            best = t
    return best


def take(w, e, it):
    """Отдать предмет игроку и погасить остальные предметы его алтаря.

    Возвращает (вид, сколько стало) или None.
    """
    u = up_of(it.kind)
    if u < 0:
        return None
    n = grant(e, u)
    w.event("pick", a=e.id, b=it.id, u=u, n=n,
            x=proto.r3(it.x), y=proto.r3(it.y))
    alt = it.alt
    doomed = [it.id]
    if alt:
        for t in w.entities.values():
            if t.id != it.id and t.alt == alt and is_item(t.kind):
                doomed.append(t.id)
    for eid in doomed:
        w.remove(eid)            # ЦЕНА: два других апгрейда этажа погасли
    return (u, n)


def resolve_pickups(w):
    """Разобрать очередь подборов. Зовётся из combat.resolve, вне итерации."""
    q = w.pickups
    if not q:
        return 0
    n = 0
    seen = set()
    for eid in q:
        if eid in seen:
            continue             # кнопка зажата: один подбор за тик на игрока
        seen.add(eid)
        e = w.entities.get(eid)
        if e is None or e.kind != world_mod.K_PLAYER:
            continue
        if e.flags & (world_mod.F_DEAD | world_mod.F_OFFLINE):
            continue             # дух не берёт предметов (8.5)
        it = nearest_item(w, e)
        if it is None:
            continue
        if take(w, e, it) is not None:
            n += 1
    del q[:]
    return n


# --- расстановка (8.4 + gen._pick_altar) ----------------------------------

ALTAR_PER = 2


def altar_count(alive):
    """Сколько алтарей положено этажу при таком числе живых (8.4).

    ВНИМАНИЕ: 8.4 САМ СЕБЕ ПРОТИВОРЕЧИТ, и здесь выбрана одна из двух его
    половин. Дословно: «Алтарей на этаж — `1 + (живых − 1) // 2` (один
    игрок — один алтарь, двое или трое — два, четверо или пятеро — три)».
    Формула и её же расшифровка расходятся на ЧЁТНЫХ:

        живых            1   2   3   4   5   6   7   8
        1 + (n-1) // 2   1   1   2   2   3   3   4   4
        слова 8.4        1   2   2   3   3   4   4   5   = 1 + n // 2

    Взяты СЛОВА, и вот по какому счёту. Алтарь даёт группе РОВНО ОДИН
    апгрейд: взял один предмет — два других гаснут (8.4). Значит апгрейдов
    на игрока за забег = алтарей * этажей / игроков. Тот самый довод 8.4
    («каждому из четверых 1.2 апгрейда за забег против пяти в одиночку»)
    считается именно так: 1 алтарь * 5 этажей / 4 игрока = 1.25. Число из
    контракта сходится с этим счётом до второго знака, то есть счёт верен.
    Дальше по нему же: четверым нужно 3 алтаря (3*5/4 = 3.75 апгрейда), а
    не 2 (2.5) — иначе вчетвером темп вдвое ниже одиночного, а лечили тут
    ровно это. Формулу надо править в контракте на `1 + живых // 2`, см.
    отчёт.

    Ноль живых — ноль алтарей: раскладывать ещё рано, см. world.altar_floor.
    """
    n = int(alive)
    if n <= 0:
        return 0
    return 1 + n // ALTAR_PER


def populate(w, fl, rnd=None, alive=None):
    """Разложить алтари этажа. Возвращает список заведённых сущностей.

    Детерминизм ровно как у врагов (ai.populate) и генератора: один Random,
    засеянный (сид, этаж), и обход СПИСКА, а не множества. Один сид — один и
    тот же выбор на алтарях, как обещает 8.7. Число алтарей от сида НЕ
    зависит и зависеть не может: это число ЖИВЫХ (8.4), а живые к карте
    отношения не имеют.

    ЖИВЫХ СЧИТАЕМ САМИ, из мира. Комната зовёт populate двумя способами: при
    спуске — когда игроки уже есть, при старте забега — когда их ещё нет
    (room.start заводит игроков ПОСЛЕ). Во втором случае раскладывать нечего
    и не по чему, поэтому этаж кладётся в w.altar_floor и раскладывается на
    первом же тике с игроками (world.step). Вариант «считать по числу мест
    в комнате» не годится: мест восемь всегда.

    ЧИТАЕТСЯ ТОЛЬКО ТО, ЧТО ЕСТЬ: у карты-заглушки из стендов (two_clients)
    никаких altars нет, и предметов там просто не будет — падать из-за
    заглушки расстановка не имеет права.
    """
    places = getattr(fl, "altars", None)
    if not places:
        # карта из времён одного алтаря (или заглушка стенда)
        one = getattr(fl, "altar_slots", None)
        if not one:
            w.altar_floor = None
            return []
        places = [(getattr(fl, "altar", None), getattr(fl, "altar_room", -1),
                   one, getattr(fl, "altar_detour", -1))]
    if alive is None:
        alive = len(w.alive_players())
    if alive <= 0:
        # Игроков ещё нет (room.start зовёт populate ДО того, как их заведёт).
        # Кладём МИНИМУМ — один алтарь: он положен любой непустой группе, то
        # есть этаж не бывает без алтаря ни одного тика. Остальные доложит
        # первый же тик с игроками (world.altar_floor -> сюда же).
        k = 1
        w.altar_floor = fl
    else:
        k = altar_count(alive)
        w.altar_floor = None
    k = min(k, len(places))
    have = w.altar_here
    if k <= have:
        return []               # столько уже лежит
    floor_n = int(getattr(fl, "floor", 1))
    if rnd is None:
        # соль своя, не как у ai.populate: одинаковая соль связала бы выбор
        # на алтаре с расстановкой врагов, и «повезло с предметом» стало бы
        # значить «повезло с бестиарием».
        rnd = random.Random(((int(getattr(fl, "seed", 0)) & 0x3FFFFFFF) * 2246822519
                             ^ (floor_n * 26699) ^ 0x17E30))
    out = []
    for n, place in enumerate(places[:k]):
        # Случайное берётся для КАЖДОГО алтаря по порядку, в том числе для
        # уже лежащих: иначе добор сдвинул бы поток и «один сид — тот же
        # выбор» (8.7) перестало бы выполняться при доборе.
        kinds = list(range(N_UP))
        rnd.shuffle(kinds)
        if n < have:
            continue                    # этот алтарь уже лежит
        slots = place[2]
        if not slots:
            continue
        # НОМЕР У КАЖДОГО АЛТАРЯ СВОЙ. На нём стоит вся цена выбора: take()
        # гасит собратьев «по МОЕМУ алтарю» по этому номеру, и общий номер
        # погасил бы весь этаж с одного предмета.
        w.altar_seq += 1
        alt = w.altar_seq
        for i, (x, y) in enumerate(slots[:ALTAR_SLOTS]):
            u = kinds[i % N_UP]
            e = w.spawn(kind_of(u), x, y, r=ITEM_R, hp=1, hp_max=1, alt=alt)
            out.append(e)
    w.altar_here = k
    return out
