# --- виды апгрейдов --------------------------------------------------------
U_HARVEST = 0
U_RAM = 1
U_RICO = 2
U_WIND = 3
U_HASTE = 4
N_UP = 5

NAMES = ("Жатва", "Таран", "Рикошет", "Ветер", "Скороход")

# kind предмета: таблица, а не K_ITEM_BASE + вид. Пятому апгрейду по старой
# арифметике достался бы kind 10, а это БОСС (4.3) — и алтарь начал бы
# раскладывать боссов, а клиент рисовать предмет телом 0.50 с полоской
# здоровья. Значения 6..9 остаются за прежними четырьмя предметами ровно
# там, где их знают клиент и проверки; пятому дано 11 — первое свободное
# после босса.
ITEM_KINDS = (6, 7, 8, 9, 11)
K_ITEM_BASE = ITEM_KINDS[0]
K_ITEM_LAST = max(ITEM_KINDS)
_UP_BY_KIND = dict((k, u) for u, k in enumerate(ITEM_KINDS))

# --- числа эффектов --------------------------------------------------------
# Все взяты от существующих чисел 4.2, и каждое названо в разах.

# Жатва: 15 hp за убитого. ВЫВОД: рубака бьёт на 20 раз в 36 тиков = 16.7
# hp/с, а умирает от двух ударов игрока (40 hp / 20) = 28 тиков = 0.93 с.
# Значит один стак Жатвы возвращает 15 / 0.93 = 16.1 hp/с — ровно дыхание
# ОДНОГО рубаки в упор. Больше — и толпа перестаёт быть опасной; меньше —
# и лечение не читается.
HARVEST_HEAL = 15

# Таран: 20 за тело = ровно ближний удар (MELEE_DMG, 4.2). Рубака (40 hp)
# умирает от «рывок + удар», стрелок (25 hp) — нет: 20 < 25, и это
# намеренно, иначе рывок обнулял бы весь дальний бестиарий с одного стака.
RAM_DMG = 20

# Рикошет: 2 отскока за стак. ВЫВОД: Г-образный коридор — это два поворота,
# то есть двух отскоков хватает, чтобы достать из-за угла и вернуться.
RICO_BOUNCES = 2

# Скороход: +2.5 кл/с к бегу за стак (треть базовых 7.5).
#
# ВЫВОД ОТ БЕСТИАРИЯ, А НЕ ОТ ПРОЦЕНТА. Игрок быстрее рядового рубаки в
# 7.5 / 4.8 = 1.56 раза, и это ровно то отношение, при котором 4.2 говорит
# «убежать можно всегда». Самое быстрое тело в игре — босс, 6.3 кл/с, и над
# ним у игрока всего 1.19. Один стак Скорохода обязан сделать с боссом то,
# что база делает с рубакой: 10.0 / 6.3 = 1.59. Отсюда +2.5, а не +0.5 и не
# +5.0. Два стака (12.5) — это 1.98 босса и 2.6 рубаки, то есть игра, в
# которой от толпы уходят пешком.
HASTE_ADD = 2.5

# ПОТОЛОК СКОРОСТИ БЕГА — ДВЕ БАЗЫ, и он не вкус, а место, где ломаются сразу
# две вещи:
#
#   * БЕГ СТАНОВИТСЯ РЫВКОМ. Рывок — это 2.8 скорости бега плюс
#     неуязвимость, и платят за него откатом 27 тиков (4.2). На 2.0 базы бег
#     даёт 0.71 скорости рывка БЕЗ отката; выше — рывок перестаёт быть
#     способом разорвать дистанцию и остаётся только неуязвимостью.
#   * БЕГ ОБГОНЯЕТ СОБСТВЕННЫЙ ОБЗОР. Радиус обзора 10 клеток (4.1). На
#     базовых 7.5 игрок пересекает его за 1.33 с, на 15.0 — за 0.67 с, а
#     замах врага, на который надо ответить, длится 0.4 с (12 тиков, 4.2).
#     Дальше бег превращается в бег вслепую: увидел — и уже в упор.
#
# Потолок достижим (три стака), поэтому он проверяется прямо, а не на словах:
# tests/items_check.py даёт десять стаков и смотрит, что скорость встала.
HASTE_CAP_K = 2.0

# Ветер: откат рывка делится на (1 + стаки). Пол — DASH_CD_FLOOR тиков:
# ниже длительности рывка (5 тиков, 4.2) откат опускать нельзя, иначе рывок
# становится не рывком, а способом передвижения. 7 = 5 тиков рывка + 2 паузы.
DASH_CD_FLOOR = 7

# ДОЛЯ НЕУЯЗВИМОСТИ ОГРАНИЧЕНА ПОЛОВИНОЙ ОТКАТА, И ЭТО НЕ ВКУС.
# Рывок даёт неуязвимость на все свои 5 тиков (4.2). Ветер откат укорачивает,
# а окно неуязвимости — нет, поэтому её ДОЛЯ растёт сама собой: при откате 27
# это 18% времени, при 14 — 36%, при 7 — 71%. Замерено, что 71% и есть
# поломка, которой боится приёмка: игрок с Ветром x3 и Тараном выходит живым
# и со 100 hp из приклеенного кольца ИЗ ДВЕНАДЦАТИ рубак (tests/items_check,
# раздел 6). Поэтому неуязвимость режется до половины отката: половина —
# наименьшая доля, при которой «рывок — это уход, а не щит» остаётся правдой,
# ведь вторую половину времени урон проходит. При откате 27/14/10 ничего не
# меняется вовсе (5 <= cd//2), режется только выжатый Ветром хвост.
DASH_INV_SHARE = 2      # неуязвимость <= откат / DASH_INV_SHARE

# --- алтарь ----------------------------------------------------------------
ALTAR_SLOTS = 3        # предметов на алтаре; берётся один
ITEM_R = 0.20          # радиус сущности предмета: меньше тела, это не тело
PICK_R = 0.80          # с какого расстояния предмет берётся
# ВЫВОД PICK_R: предмет стоит в центре клетки, радиус игрока 0.35 (4.1).
# 0.80 — это «стою на клетке предмета или вплотную к ней»: центр игрока
# может отойти от центра клетки на 0.5*sqrt(2)=0.71 и всё ещё стоять на
# ней. Меньше 0.71 — и предмет нельзя взять, стоя на нём по диагонали.
MAX_PICKUPS = 16       # предохранитель очереди, как у world.MAX_NOISES


def kind_of(u):
    """Вид апгрейда -> kind сущности предмета (4.3)."""
    return ITEM_KINDS[u] if 0 <= u < N_UP else -1


def up_of(kind):
    """kind сущности -> вид апгрейда, или -1 если это не предмет."""
    return _UP_BY_KIND.get(kind, -1)


def is_item(kind):
    return kind in _UP_BY_KIND


# --- состояние владельца ---------------------------------------------------
# Хранится в e.ups: None (ничего не собрано) или список счётчиков длины N_UP.
# Список, а не набор флагов, именно потому, что 8.4 требует СКЛАДЫВАНИЯ:
# «есть апгрейд» — это число, а не да/нет.

def count(e, u):
    ups = e.ups
    return ups[u] if ups else 0


def total(e):
    ups = e.ups
    return sum(ups) if ups else 0


def grant(e, u, n=1):
    """Выдать n стаков апгрейда. Возвращает, сколько стало."""
    if not (0 <= u < N_UP):
        return 0
    ups = e.ups
    if ups is None:
        ups = [0] * N_UP
        e.ups = ups
    ups[u] += n
    return ups[u]


def describe(e):
    """Читаемый набор: [(вид, сколько)] — для отчётов и проверок."""
    ups = e.ups
    if not ups:
        return []
    return [(u, ups[u]) for u in range(N_UP) if ups[u]]


# --- эффекты: единственное место, где апгрейд превращается в число ---------
# Бой зовёт эти функции, а не заглядывает в e.ups. Поэтому «апгрейд не
# применился» и «апгрейд не сложился» — две разные поломки в двух разных
# строках, и проверка умеет отличить одну от другой.

def kill_heal(e):
    """Сколько hp возвращает убийство (Жатва). 0 — апгрейда нет."""
    return HARVEST_HEAL * count(e, U_HARVEST)


def dash_dmg(e):
    """Урон рывка по телу на пути (Таран). 0 — апгрейда нет."""
    return RAM_DMG * count(e, U_RAM)


def shot_bounces(e):
    """Сколько раз снаряд отскочит от стены вместо гибели (Рикошет)."""
    return RICO_BOUNCES * count(e, U_RICO)


def run_speed(e, base):
    """Скорость бега с учётом Скорохода. base — своё число сущности.

    Зовётся из world.step на ветке управляемого тела, то есть ровно там, где
    рулёжка превращается в скорость. Врагов не касается вовсе: у них e.ups
    пуст, count вернёт 0, и base уйдёт обратно тем же числом.
    """
    k = count(e, U_HASTE)
    if not k:
        return base
    top = base * HASTE_CAP_K
    v = base + HASTE_ADD * k
    return top if v > top else v


def dash_cd(e, base):
    """Откат рывка с учётом Ветра. base — число тиков из combat (4.2)."""
    k = count(e, U_WIND)
    if not k:
        return base
    cd = int(round(base / float(1 + k)))
    return cd if cd > DASH_CD_FLOOR else DASH_CD_FLOOR


def dash_inv(base_inv, cd):
    """Сколько тиков длится неуязвимость рывка при таком откате.

    Без Ветра возвращает ровно base_inv (число 4.2): 5 <= 27 // 2. Смысл
    появляется только на укороченном откате — см. DASH_INV_SHARE.
    """
    half = cd // DASH_INV_SHARE
    if base_inv <= half:
        return base_inv
    return half if half >= 1 else 1


# --- лечение ---------------------------------------------------------------

def heal(e, amount):
    """Добавить hp, не выше hp_max. Возвращает, сколько добавилось на самом деле.

    Мёртвый не лечится: 8.5 говорит, что дух воскресает этажом ниже, а не от
    чужой смерти. Иначе Жатва воскрешала бы напарника чужим убийством.
    """
    if amount <= 0 or e.hp <= 0 or (e.flags & world_mod.F_DEAD):
        return 0
    hp = e.hp + amount
    if hp > e.hp_max:
        hp = e.hp_max
    got = hp - e.hp
    e.hp = hp
    return got


# --- ОПЫТ И УРОВНИ (8.4a) --------------------------------------------------
#
# ЗАЧЕМ. До этого апгрейды давал ТОЛЬКО алтарь — один выбор на этаж, за
# которым надо идти крюком. Награда не зависела от боя вовсе: убил тридцать
# врагов или обежал их — получил одно и то же. Опыт делает бой выгодным сам
# по себе, а уровень закрывает вторую дыру: внутри этажа здоровье не
# восстанавливается ничем, кроме Жатвы (8.5), то есть лечение есть только у
# того, кто уже вытянул нужный предмет. Уровень лечит честно: хочешь
# лечиться — дерись.
#
# АЛТАРИ ОСТАЮТСЯ. Это два РАЗНЫХ выбора, а не два крана одного: алтарь
# редкий и платится дорогой вниз (крюк медиана 60 клеток, 8.4), уровень
# частый и платится риском — за опытом надо лезть в толпу.
#
# СКОЛЬКО ОПЫТА СТОИТ ЦЕЛЬ — hp_max, И НИ ОДНОЙ НОВОЙ КОНСТАНТЫ. Цена врага
# для группы это ровно то, сколько по нему надо бить: рубака 40, стрелок 25,
# босс 400 (4.2). Отсюда же «средний рядовой» = 35: две трети рубак и треть
# стрелков (ai.RANGED_EVERY), то самое число, от которого ai.py считает
# суммарное здоровье этажа.
#
# ФОРМА КРИВОЙ ВЫВЕДЕНА, А НЕ НАЗНАЧЕНА, И ОНА ЕДИНСТВЕННАЯ.
# Врагов на этаже 8 + 4*(этаж-1) (8.1), то есть ПРИТОК опыта растёт линейно
# по этажу, а НАКОПЛЕННЫЙ опыт — квадратично. Дальше всё решает форма порога:
#
#   * порог постоянный (уровень всегда стоит столько же) — число уровней
#     растёт как квадрат этажа: к 20-му их вчетверо больше, чем к 10-му, и
#     вшестнадцатеро больше, чем к 5-му. Это и есть то самое «к десятому
#     этажу враги перестают существовать»;
#   * порог, растущий линейно (уровень L стоит XP_STEP * L), превращает
#     квадратичный приток в ЛИНЕЙНОЕ число уровней: L ~ sqrt(2*опыт/STEP), а
#     опыт ~ этаж^2, значит уровней на этаж — постоянно, на любой глубине.
#
# Поэтому порог растёт линейно. Это следствие 8.1, а не вкус, и оно не
# зависит от того, какое число стоит в XP_STEP.
#
# МАСШТАБ (XP_STEP) — ТРИ РЯДОВЫХ. Первый уровень стоит трёх средних
# рядовых, второй — ещё шести, L-й — ещё 3L. Почему три, а не один и не
# десять: один враг сделал бы уровень шумом (на первом этаже их восемь,
# 8.1), а десять — недостижимой редкостью на первых этажах, где их всего
# восемь. Три — это «зачистил комнату», наименьшая единица боя, которая уже
# является боем. Числа, которые из этого выходят, замерены и названы в
# отчёте; ниже — то же самое в одну строку.
XP_STEP = 105           # 3 средних рядовых по 35 hp


def xp_for(victim):
    """Сколько опыта стоит эта цель. Это её hp_max и ничего больше."""
    return int(victim.hp_max)


def level_cost(lvl):
    """Сколько опыта нужно, чтобы уйти с уровня lvl на следующий."""
    return XP_STEP * (lvl + 1)


def xp_total_for(lvl):
    """Сколько опыта всего набрано к уровню lvl (для отчётов и проверок)."""
    return XP_STEP * lvl * (lvl + 1) // 2


# ЛЕЧЕНИЕ НА УРОВНЕ — 40 hp, И У ЭТОГО ЧИСЛА ДВА НЕЗАВИСИМЫХ ВЫВОДА.
#
#   * ПОТОЛОК СВЕРХУ ОТ ЖАТВЫ. Жатва — это апгрейд, ВЕСЬ смысл которого в
#     лечении (15 hp за убийство, 8.4). Если уровень лечит больше, чем Жатва
#     успевает за то же число убийств, Жатву не возьмёт никто. Уровень L
#     стоит 3L убийств, самый дешёвый — первый, три убийства. Значит
#     лечение уровня обязано быть меньше 3 * 15 = 45 hp. 40 даёт 13.3 hp за
#     убийство на первом уровне и 2.7 на пятом — ниже одного стака Жатвы на
#     ЛЮБОМ уровне, то есть Жатва остаётся лекарством, а уровень — спасением.
#   * СНИЗУ ОТ ЦЕНЫ СМЕРТИ. Воскрешение даёт половину здоровья (REVIVE_SHARE
#     ниже), то есть смерть стоит 50 hp. Уровень возвращает 40 из них: один
#     уровень почти отыгрывает одну смерть, но не полностью — иначе смерть
#     снова становится бесплатной, только другим путём.
#
# В разах: 40 hp это два удара рубаки (20 каждый, 4.2), то есть уровень
# выкупает ровно две ошибки, и 2.4 с рубаки в упор (16.7 hp/с — вывод
# HARVEST_HEAL). Из плохого размена он вытаскивает, из боя — нет.
LEVEL_HEAL = 40

# ВЫБОР НА УРОВНЕ ВЫКЛАДЫВАЕТСЯ ПРЕДМЕТАМИ, А НЕ НОВЫМ СООБЩЕНИЕМ.
# Это решение про ПРОВОД, и оно стоит ноль: предмет — уже существующая
# сущность со своим kind (4.3), клиент её уже рисует, подбор уже уходит
# событием pick, набор уже уходит сообщением build (11.7). Новое сообщение
# «выбери из трёх» потребовало бы правки proto.py, room.py и клиента —
# чужих файлов, — а дало бы ровно то же самое.
LEVEL_SLOTS = 3         # столько же, сколько на алтаре (ALTAR_SLOTS)
LEVEL_RING = 0.75       # на каком расстоянии от игрока лежит выбор
# ВЫВОД LEVEL_RING: подбор работает до PICK_R = 0.80 (см. выше), значит
# 0.75 — это «всё три лежат в руках, но не в одной точке». Шаг в 0.1 клетки
# меняет, какой из них ближайший, то есть выбор делается НОГАМИ и без единой
# новой кнопки. Дальше 0.80 класть нельзя: тогда за собственным уровнем
# пришлось бы идти, а уровень — награда за бой, который идёт прямо сейчас.


def _offer_rnd(w, e):
    """Свой поток случайного на каждый уровень: 8.7 обещает один сид — один
    забег, и выбор на уровне обязан повторяться так же, как выбор на алтаре.
    Соль своя, не как у алтаря и не как у врагов, иначе «повезло с уровнем»
    стало бы значить «повезло с бестиарием»."""
    return random.Random(((int(getattr(w, "seed", 0)) & 0x3FFFFFFF) * 2654435761
                          ^ (int(e.id) * 2246822519)
                          ^ (int(e.lvl) * 40503) ^ 0x1EE11))


def offer_items(w, e):
    """Выложить вокруг игрока выбор из LEVEL_SLOTS апгрейдов. Вернуть alt.

    Меняет состав мира, поэтому зовётся ТОЛЬКО из resolve_levels, то есть
    вне прохода по словарю сущностей, — ровно по тому же правилу, по
    которому здесь же живёт очередь подбора.
    """
    kinds = list(range(N_UP))
    _offer_rnd(w, e).shuffle(kinds)
    w.altar_seq += 1
    alt = w.altar_seq
    step = 2.0 * math.pi / LEVEL_SLOTS
    for i in range(LEVEL_SLOTS):
        a = e.facing + i * step
        x = e.x + math.cos(a) * LEVEL_RING
        y = e.y + math.sin(a) * LEVEL_RING
        x, y = physics.free_spot(w.grid, x, y, ITEM_R)
        w.spawn(kind_of(kinds[i % N_UP]), x, y, r=ITEM_R, hp=1, hp_max=1,
                alt=alt, owner=e.id)
    return alt


# ВЫКЛЮЧАТЕЛЬ ДЛЯ СТЕНДОВ, А НЕ ДЛЯ ИГРЫ — тот же приём и тот же довод, что
# у ai.ENEMIES_ON (правило 10: «стенд обязан уметь выключать то, что он не
# меряет»). Нужен он вот зачем: уровень ЛЕЧИТ, и любая проверка, которая
# меряет лечение чем-то другим — Жатвой, запасом здоровья за этаж, ценой
# смерти, — получает чужую прибавку в свой столбец. Стенд, который меряет
# Жатву, гасит опыт на время мерки; игра его не гасит никогда.
XP_ON = os.environ.get("ZZA_XP", "1") != "0"


def add_xp(w, e, amount):
    """Начислить опыт и поднять уровни. Возвращает, сколько уровней прибавилось.

    Уровень здесь только НАЧИСЛЯЕТСЯ и ЛЕЧИТ; выбор выкладывает
    resolve_levels, потому что выкладывание меняет состав мира, а зовут нас
    из combat.damage, то есть из-под прохода по сущностям.
    """
    if not XP_ON or amount <= 0 or e.kind != world_mod.K_PLAYER:
        return 0
    if e.flags & world_mod.F_DEAD:
        return 0                 # дух не дерётся (8.5), значит и не растёт
    e.xp += int(amount)
    got = 0
    while e.xp >= level_cost(e.lvl):
        e.xp -= level_cost(e.lvl)
        e.lvl += 1
        got += 1
        e.lvl_owed += 1
        heal(e, LEVEL_HEAL)
        w.event("lvl", a=e.id, b=e.lvl, n=e.lvl,
                x=proto.r3(e.x), y=proto.r3(e.y))
    if got:
        _queue_level(w, e)
    return got


def _queue_level(w, e):
    """Поставить игрока в очередь на выкладку выбора."""
    if e.id not in w.level_q:
        w.level_q.append(e.id)


def resolve_levels(w):
    """Выложить выбор тем, кто его ждёт. Зовётся из combat.resolve.

    Одновременно на полу лежит НЕ БОЛЬШЕ ОДНОГО выбора на игрока: пока
    прошлый не взят, следующий ждёт в e.lvl_owed. Иначе игрок, взявший три
    уровня в одной волне, оставлял бы за собой девять сущностей, а клиент —
    девять кружков в куче. Долг не теряется: его подберёт take() и смена
    этажа.
    """
    q = w.level_q
    if not q:
        return 0
    n = 0
    for eid in q:
        e = w.entities.get(eid)
        if e is None or e.kind != world_mod.K_PLAYER:
            continue
        if e.offer or e.lvl_owed <= 0:
            continue
        if e.flags & (world_mod.F_DEAD | world_mod.F_OFFLINE):
            continue             # духу выбирать нечего, долг подождёт спуска
        e.lvl_owed -= 1
        e.offer = offer_items(w, e)
        n += 1
    del q[:]
    return n


# --- ЦЕНА СМЕРТИ (8.5, дыра 11.8) -----------------------------------------
#
# ЧТО БЫЛО ИЗМЕРЕНО. Вчетвером до 20-го этажа доходили 10 забегов из 10
# (11.8). Причина названа там же — бесплатное воскрешение, но она сильнее,
# чем «бесплатное»: смерть была ВЫГОДНОЙ. Мёртвый воскресал этажом ниже с
# ПОЛНЫМ здоровьем, а лестница ждёт только живых (8.1) — то есть смерть
# работала как полное лечение плюс бесплатный перенос к лестнице. Группе из
# четверых достаточно было держать одного живого.
#
# ЧТО СДЕЛАНО. Воскрешение тратит ОБЩИЙ СЧЁТЧИК ГРУППЫ и возвращает
# ПОЛОВИНУ здоровья. Счётчик кончился — дух остаётся духом: он по-прежнему
# летает, видит и слышит (8.5), то есть перед серым экраном не сидит никто,
# ради чего правило 8.5 и писалось.
#
# ПОЧЕМУ ОБЩИЙ, А НЕ ЛИЧНЫЙ. Личный счётчик чинит одного игрока, а дыра —
# групповая: группа гоняет на убой того, у кого осталось. Общий счётчик
# делает смерть напарника СВОИМ убытком, и это ровно то, чего у группы не
# было — чем рисковать.
#
# ПОЧЕМУ НЕ ДРУГИЕ ТРИ. Рассмотрены все, и отвергнуты числом, а не вкусом:
#
#   * ЛЕСТНИЦА ЖДЁТ И ДУХОВ. Группа встаёт намертво: воскрешать духа негде,
#     кроме следующего этажа, а на следующий этаж без него не уйти. Это не
#     цена смерти, это конец забега на первой же смерти — вчетвером было бы
#     0 из 10, и противоречит 8.1 прямым текстом.
#   * СМЕРТЬ ОТНИМАЕТ ЧАСТЬ НАБОРА. Бьёт по тому, кто и так проигрывает, и
#     ровно в ту сторону, в которую он проигрывает: потерял апгрейды —
#     умираешь чаще — теряешь ещё. Плюс 8.4 прямым текстом обещает, что
#     набор переживает смерть, а с опытом (выше) это уже не «часть набора»,
#     а откат прогресса.
#   * ПОЛОВИНА ЗДОРОВЬЯ С ПАДАЮЩИМ ПОТОЛКОМ. Спираль, которую 8.4 уже
#     отверг в другом месте («фиксированная цена в hp за пять этажей —
#     спираль смерти»): потолок только падает, отыграть его нечем.
#     Половина здоровья БЕЗ падающего потолка взята — см. REVIVE_SHARE, —
#     потому что отыграть её теперь есть чем: уровень лечит на 40.
#
# ОТКУДА ЧИСЛА. Замерено на исходном дереве (tests/run_depth.py плюс разбор
# событий die): за полный забег до 20-го этажа вчетвером игроки умирают
# 4..13 раз, медиана 7; вдвоём — 1..6, медиана 2; в одиночку смерть одна и
# она же конец забега. Значит счётчик должен стоять НИЖЕ семи, иначе он не
# тратится ни разу, и ВЫШЕ нуля, иначе первая же смерть окончательна.
REVIVE_BASE = 2         # зарядов у группы на старте забега
REVIVE_PER_BOSS = 1     # босс возвращает один (8.1: босс каждый пятый этаж)
REVIVE_SHARE = 0.5      # воскрешение даёт эту долю hp_max
# ВЫВОД REVIVE_BASE = 2. Это «группа имеет право на две ошибки бесплатно» —
# меньше медианы смертей (7) втрое, то есть счётчик заведомо кончается и
# заведомо не с первой смерти. Пополнение привязано к боссу, а не к находке
# на полу: босс — единственное событие забега, которое нельзя обойти (8.1
# запирает лестницу), значит пополнение нельзя ни пропустить, ни
# фармить. За полный забег до 20-го этажа босса бьют четырежды (этажи 5, 10,
# 15, 20), то есть всего зарядов 2 + 4 = 6 против медианы 7 смертей —
# счётчик кончается примерно там, где группа и так шла на дно.
# ВЫВОД REVIVE_SHARE = 0.5: 50 hp это 2.5 удара рубаки (20, 4.2) — воскресший
# играет, но следующая ошибка стоит ему жизни. Полное здоровье делало смерть
# лечением, а четверть (25 hp) — одним ударом, то есть воскрешением в никуда.


def revive_cost(w):
    """Хватает ли группе заряда на одно воскрешение."""
    return w.revives > 0


def spend_revive(w):
    """Потратить заряд. True — потрачен, False — нечего тратить."""
    if w.revives <= 0:
        return False
    w.revives -= 1
    return True


def add_revive(w, n=REVIVE_PER_BOSS):
    """Вернуть группе заряд (босс, 8.1)."""
    w.revives += int(n)
    w.event("rev", a=0, b=w.revives, n=w.revives)
    return w.revives


# --- рывок-таран -----------------------------------------------------------

def dash_strike(w, e, damage_fn):
    """Урон телам, сквозь которые прошёл рывок. Раз за рывок на тело.

    Зовётся из combat.resolve, то есть ПОСЛЕ движения: тело уже там, где
    оно оказалось в этом тике. Список уже задетых живёт в e.dash_hit и
    обнуляется на старте рывка — без него один рывок бил бы одну и ту же
    цель все 5 тиков, то есть впятеро.
    """
    dmg = dash_dmg(e)
    if dmg <= 0:
        return 0
    hits = e.dash_hit
    if hits is None:
        hits = []
        e.dash_hit = hits
    n = 0
    for t in w.entities.values():
        if t is e or t.id in hits:
            continue
        if t.kind == world_mod.K_SHOT or not t.team or t.team == e.team:
            continue                 # свои и снаряды тараном не берутся
        if t.flags & world_mod.F_DEAD:
            continue
        dx = t.x - e.x
        dy = t.y - e.y
        rr = e.r + t.r
        if dx * dx + dy * dy > rr * rr:
            continue
        hits.append(t.id)
        if damage_fn(w, t, dmg, e):
            n += 1
    return n


# --- подбор (бит 16 в btn, 5.1) -------------------------------------------

def request_pickup(w, e):
    """Кнопка предмета нажата. Сам подбор — в resolve_pickups.

    Класть предмет в руки прямо здесь нельзя: begin() зовётся ИЗ цикла по
    словарю сущностей (world.step), а подбор этот словарь меняет — предмет
    исчезает, и вместе с ним его собратья по алтарю. Та же причина, по
    которой снаряд рождается в resolve, а не в begin.
    """
    if len(w.pickups) < MAX_PICKUPS:
        w.pickups.append(e.id)


def nearest_item(w, e):
    """Ближайший предмет в радиусе PICK_R, или None.

    ЧУЖОЙ ВЫБОР НА УРОВНЕ НЕ БЕРЁТСЯ. У предмета с алтаря owner равен нулю —
    он общий, за него группа и торгуется (8.4). У предмета, выложенного
    уровнем, owner это id того, кто уровень получил: награда за ЕГО бой, и
    напарник, пробегающий мимо, не имеет права её подобрать. Поле owner в
    сущности уже есть (им пользуется снаряд — «чей»), на провод оно не
    уходит, то есть 4.3 не трогается ни на байт.
    """
    best = None
    best_d2 = PICK_R * PICK_R
    for t in w.entities.values():
        if not is_item(t.kind):
            continue
        if t.owner and t.owner != e.id:
            continue
        dx = t.x - e.x
        dy = t.y - e.y
        d2 = dx * dx + dy * dy
        if d2 <= best_d2:
            best_d2 = d2
            best = t
    return best


def take(w, e, it):
    """Отдать предмет игроку и погасить остальные предметы его алтаря.

    Возвращает (вид, сколько стало) или None.
    """
    u = up_of(it.kind)
    if u < 0:
        return None
    n = grant(e, u)
    w.event("pick", a=e.id, b=it.id, u=u, n=n,
            x=proto.r3(it.x), y=proto.r3(it.y))
    alt = it.alt
    doomed = [it.id]
    if alt:
        for t in w.entities.values():
            if t.id != it.id and t.alt == alt and is_item(t.kind):
                doomed.append(t.id)
    for eid in doomed:
        w.remove(eid)            # ЦЕНА: два других апгрейда этажа погасли
    # Выбор, выложенный уровнем, закрыт — можно выкладывать следующий долг.
    if alt and e.offer == alt:
        e.offer = 0
        if e.lvl_owed > 0:
            _queue_level(w, e)
    return (u, n)


def resolve_pickups(w):
    """Разобрать очередь подборов. Зовётся из combat.resolve, вне итерации."""
    q = w.pickups
    if not q:
        return 0
    n = 0
    seen = set()
    for eid in q:
        if eid in seen:
            continue             # кнопка зажата: один подбор за тик на игрока
        seen.add(eid)
        e = w.entities.get(eid)
        if e is None or e.kind != world_mod.K_PLAYER:
            continue
        if e.flags & (world_mod.F_DEAD | world_mod.F_OFFLINE):
            continue             # дух не берёт предметов (8.5)
        it = nearest_item(w, e)
        if it is None:
            continue
        if take(w, e, it) is not None:
            n += 1
    del q[:]
    return n


# --- расстановка (8.4 + gen._pick_altars) ----------------------------------

ALTAR_PER = 2


def altar_count(alive):
    """Сколько алтарей положено этажу при таком числе живых (8.4).

    ВНИМАНИЕ: 8.4 САМ СЕБЕ ПРОТИВОРЕЧИТ, и здесь выбрана одна из двух его
    половин. Дословно: «Алтарей на этаж — `1 + (живых − 1) // 2` (один
    игрок — один алтарь, двое или трое — два, четверо или пятеро — три)».
    Формула и её же расшифровка расходятся на ЧЁТНЫХ:

        живых            1   2   3   4   5   6   7   8
        1 + (n-1) // 2   1   1   2   2   3   3   4   4
        слова 8.4        1   2   2   3   3   4   4   5   = 1 + n // 2

    Взяты СЛОВА, и вот по какому счёту. Алтарь даёт группе РОВНО ОДИН
    апгрейд: взял один предмет — два других гаснут (8.4). Значит апгрейдов
    на игрока за забег = алтарей * этажей / игроков. Тот самый довод 8.4
    («каждому из четверых 1.2 апгрейда за забег против пяти в одиночку»)
    считается именно так: 1 алтарь * 5 этажей / 4 игрока = 1.25. Число из
    контракта сходится с этим счётом до второго знака, то есть счёт верен.
    Дальше по нему же: четверым нужно 3 алтаря (3*5/4 = 3.75 апгрейда), а
    не 2 (2.5) — иначе вчетвером темп вдвое ниже одиночного, а лечили тут
    ровно это. Формулу надо править в контракте на `1 + живых // 2`, см.
    отчёт.

    Ноль живых — ноль алтарей: раскладывать ещё рано, см. world.altar_floor.
    """
    n = int(alive)
    if n <= 0:
        return 0
    return 1 + n // ALTAR_PER


def populate(w, fl, rnd=None, alive=None):
    """Разложить алтари этажа. Возвращает список заведённых сущностей.

    Детерминизм ровно как у врагов (ai.populate) и генератора: один Random,
    засеянный (сид, этаж), и обход СПИСКА, а не множества. Один сид — один и
    тот же выбор на алтарях, как обещает 8.7. Число алтарей от сида НЕ
    зависит и зависеть не может: это число ЖИВЫХ (8.4), а живые к карте
    отношения не имеют.

    ЖИВЫХ СЧИТАЕМ САМИ, из мира. Комната зовёт populate двумя способами: при
    спуске — когда игроки уже есть, при старте забега — когда их ещё нет
    (room.start заводит игроков ПОСЛЕ). Во втором случае раскладывать нечего
    и не по чему, поэтому этаж кладётся в w.altar_floor и раскладывается на
    первом же тике с игроками (world.step). Вариант «считать по числу мест
    в комнате» не годится: мест восемь всегда.

    ЧИТАЕТСЯ ТОЛЬКО ТО, ЧТО ЕСТЬ: у карты-заглушки из стендов (two_clients)
    никаких altars нет, и предметов там просто не будет — падать из-за
    заглушки расстановка не имеет права.
    """
    places = getattr(fl, "altars", None)
    if not places:
        # карта из времён одного алтаря (или заглушка стенда)
        one = getattr(fl, "altar_slots", None)
        if not one:
            w.altar_floor = None
            return []
        places = [(getattr(fl, "altar", None), getattr(fl, "altar_room", -1),
                   one, getattr(fl, "altar_detour", -1))]
    if alive is None:
        alive = len(w.alive_players())
    if alive <= 0:
        # Игроков ещё нет (room.start зовёт populate ДО того, как их заведёт).
        # Кладём МИНИМУМ — один алтарь: он положен любой непустой группе, то
        # есть этаж не бывает без алтаря ни одного тика. Остальные доложит
        # первый же тик с игроками (world.altar_floor -> сюда же).
        k = 1
        w.altar_floor = fl
    else:
        k = altar_count(alive)
        w.altar_floor = None
    k = min(k, len(places))
    have = w.altar_here
    if k <= have:
        return []               # столько уже лежит
    floor_n = int(getattr(fl, "floor", 1))
    if rnd is None:
        # соль своя, не как у ai.populate: одинаковая соль связала бы выбор
        # на алтаре с расстановкой врагов, и «повезло с предметом» стало бы
        # значить «повезло с бестиарием».
        rnd = random.Random(((int(getattr(fl, "seed", 0)) & 0x3FFFFFFF) * 2246822519
                             ^ (floor_n * 26699) ^ 0x17E30))
    out = []
    for n, place in enumerate(places[:k]):
        # Случайное берётся для КАЖДОГО алтаря по порядку, в том числе для
        # уже лежащих: иначе добор сдвинул бы поток и «один сид — тот же
        # выбор» (8.7) перестало бы выполняться при доборе.
        kinds = list(range(N_UP))
        rnd.shuffle(kinds)
        if n < have:
            continue                    # этот алтарь уже лежит
        slots = place[2]
        if not slots:
            continue
        # НОМЕР У КАЖДОГО АЛТАРЯ СВОЙ. На нём стоит вся цена выбора: take()
        # гасит собратьев «по МОЕМУ алтарю» по этому номеру, и общий номер
        # погасил бы весь этаж с одного предмета.
        w.altar_seq += 1
        alt = w.altar_seq
        for i, (x, y) in enumerate(slots[:ALTAR_SLOTS]):
            u = kinds[i % N_UP]
            e = w.spawn(kind_of(u), x, y, r=ITEM_R, hp=1, hp_max=1, alt=alt)
            out.append(e)
    w.altar_here = k
    return out
