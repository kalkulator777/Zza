# -*- coding: utf-8 -*-
"""Предметы и апгрейды забега (DESIGN.md 8.4).

Внутри забега, без мета-прогрессии. Апгрейды СКЛАДЫВАЮТСЯ: второй такой же
не заменяет первый, а удваивает число, и это единственное правило, которое
здесь нельзя нарушать — на нём держится смысл второго забега.

ПЯТЬ АПГРЕЙДОВ, И ВСЕ ПЯТЬ МЕНЯЮТ ПРАВИЛО, А НЕ ПРОЦЕНТ. 8.4 писался до
того, как появился бой, и разрешает «модификаторы характеристик»; но +10% к
урону через десять минут не делает игру другой, а ради этого в рогалик и
играют второй раз. Поэтому три апгрейда меняют правило прямо, а два
(«Ветер» и «Скороход») — число, но в разы:

* **Жатва** — убийство лечит на HARVEST_HEAL за стак. Правило, которое это
  отменяет: «внутри этажа здоровье не восстанавливается» (8.5 даёт лечение
  только смертью и спуском). Самоограничение встроено: лечит не попадание, а
  ДОБИВАНИЕ, то есть ровно то действие, которое и так убирает урон с поля.
* **Таран** — рывок наносит RAM_DMG за стак каждому телу, сквозь которое
  прошёл, по разу за рывок. Правило, которое это меняет: рывок из бегства
  (неуязвимость, 4.2) становится оружием. Тела врагов для игрока проницаемы
  (расталкиваются только враги между собой, 4.2a), так что «сквозь» здесь —
  не фигура речи.
* **Рикошет** — снаряд не гибнет о стену, а отскакивает RICO_BOUNCES раз за
  стак. Правило, которое это меняет: 4.2a «прямая линия входит в смысл
  снаряда» — теперь только до первой стены. Дальность НЕ растёт: живёт
  снаряд по-прежнему ttl тиков (14 клеток), меняется лишь то, чем кончается
  встреча со стеной.
* **Ветер** — откат рывка DASH_CD / (1 + стаки). Это число, а не правило, и
  взят он ради сочетания: Ветер + Таран превращает рывок в основное оружие,
  а Ветер + Рикошет — в способ разорвать дистанцию и достать из-за угла.
  Вместе с ним приходит единственное ОГРАНИЧЕНИЕ в этом файле: неуязвимость
  рывка не имеет права занять больше половины отката (DASH_INV_SHARE), иначе
  сложенный трижды Ветер превращает уход в постоянный щит — замерено, было
  71% времени и бессмертие в кольце из двенадцати рубак.
* **Скороход** — скорость бега +HASTE_ADD за стак, потолок HASTE_CAP_K базы.
  Правило, которое это отменяет: «скорость бега — врождённое число, быстрее
  можно только рывком, и за это платят откатом» (4.2). Число здесь тоже не
  процент: один стак поднимает игрока над САМЫМ быстрым телом бестиария
  ровно настолько, насколько база поднимает его над рядовым рубакой, —
  вывод у HASTE_ADD. Потолок нужен по той же причине, по какой Ветру нужен
  пол: без него апгрейд отменяет не правило, а механику — бег догнал бы
  рывок, и рывок остался бы одной неуязвимостью.

ЦЕНА. «Апгрейд, который падает в руки» — это подарок, а не решение, поэтому
предметы лежат на АЛТАРЕ: ALTAR_SLOTS штуки разных видов в одной комнате,
берётся ОДИН — остальные гаснут в тот же тик. Платит игрок дважды:

* отказом: 2 из 3 апгрейдов этажа теряются навсегда;
* крюком: алтарь ставится в комнате с наибольшим КРЮКОМ с дороги вниз (см.
  gen._pick_altars), то есть за него платят временем в темноте и врагами,
  которых можно было обойти. Отказаться от крюка — законный ход: тогда этаж
  проходится быстрее, но забег остаётся прежним.

Кровью алтарь не берёт СОЗНАТЕЛЬНО: здоровье внутри этажа не
восстанавливается (8.5), фиксированная цена в hp за 4-5 этажей превратила бы
апгрейды в спираль смерти, а Жатву — в обязательный первый выбор.

НА ПРОВОДЕ. Предмет — обычная сущность (4.3): свой `kind` на каждый вид,
ровно по тому же доводу, по которому 4.2 развёл рубаку и стрелка разными
значениями `kind`, а не битом в `flags`, — игрок обязан ВИДЕТЬ, что он
выбирает, до того как нажмёт. Незнакомый `kind` клиент рисует серым кружком
(4.3), то есть старый клиент от новых предметов не падает, а новый рисует их
как захочет. Подбор уходит событием `pick` (5.2): восстановить его из
снапшота нельзя — предмет просто исчезает.

ЧЕГО НА ПРОВОДЕ НЕТ: набора апгрейдов игрока. 4.3 даёт ровно десять полей, и
одиннадцатого («что я собрал») там нет, а 5.2 запрещает держать состояние на
событиях. Правка контракта предложена в отчёте; пока `pick` несёт `u` (вид)
и `n` (сколько стало), так что потерянное событие чинится следующим.
"""

